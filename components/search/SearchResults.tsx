import type { AutocompleteCollection } from "@algolia/autocomplete-core";
import clsx from "clsx";
import { Fragment, useId } from "react";

import { navigation } from "@/lib/navigation";
import type { Result } from "@/lib/search";
import { NoResultsIcon } from "./icons";
import type { Autocomplete } from "./useAutocomplete";

function HighlightQuery({ text, query }: { text: string; query: string }) {
    const pattern = query.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

    // Splitting on a capturing group keeps the matches, at the odd indexes
    return text.split(new RegExp(`(${pattern})`, "i")).map((part, index) =>
        index % 2 === 1 ? (
            <mark
                key={index}
                className="underline bg-transparent text-brand-500"
            >
                {part}
            </mark>
        ) : (
            part
        ),
    );
}

function SearchResult({
    result,
    resultIndex,
    autocomplete,
    collection,
    query,
}: {
    result: Result;
    resultIndex: number;
    autocomplete: Autocomplete;
    collection: AutocompleteCollection<Result>;
    query: string;
}) {
    const id = useId();

    const sectionTitle = navigation.find((section) =>
        section.links.find((link) => link.href === result.url.split("#")[0]),
    )?.title;
    const hierarchy = [sectionTitle, result.pageTitle].filter(
        (x): x is string => typeof x === "string",
    );

    return (
        <li
            className={clsx(
                "group block cursor-default px-4 py-3 aria-selected:bg-zinc-50 dark:aria-selected:bg-zinc-800/50",
                resultIndex > 0 &&
                    "border-t border-zinc-100 dark:border-zinc-800",
            )}
            aria-labelledby={`${id}-hierarchy ${id}-title`}
            {...autocomplete.getItemProps({
                item: result,
                source: collection.source,
            })}
        >
            <div
                id={`${id}-title`}
                aria-hidden="true"
                className="text-sm font-medium text-zinc-900 group-aria-selected:text-brand-500 dark:text-white"
            >
                <HighlightQuery text={result.title} query={query} />
            </div>
            {hierarchy.length > 0 && (
                <div
                    id={`${id}-hierarchy`}
                    aria-hidden="true"
                    className="mt-1 truncate whitespace-nowrap text-2xs text-zinc-500"
                >
                    {hierarchy.map((item, itemIndex, items) => (
                        <Fragment key={item}>
                            <HighlightQuery text={item} query={query} />
                            <span
                                className={
                                    itemIndex === items.length - 1
                                        ? "sr-only"
                                        : "mx-2 text-zinc-300 dark:text-zinc-700"
                                }
                            >
                                /
                            </span>
                        </Fragment>
                    ))}
                </div>
            )}
        </li>
    );
}

export function SearchResults({
    autocomplete,
    query,
    collection,
    indexMissing,
}: {
    autocomplete: Autocomplete;
    query: string;
    collection: AutocompleteCollection<Result>;
    indexMissing: boolean;
}) {
    if (indexMissing) {
        return (
            <p className="p-6 text-center text-xs text-zinc-700 dark:text-zinc-400">
                The search index couldn&rsquo;t be loaded. It&rsquo;s only
                generated by <code>deno task build</code>, so search
                doesn&rsquo;t work in <code>deno task dev</code>.
            </p>
        );
    }

    if (collection.items.length === 0) {
        return (
            <div className="p-6 text-center">
                <NoResultsIcon className="mx-auto h-5 w-5 stroke-zinc-900 dark:stroke-zinc-600" />
                <p className="mt-2 text-xs text-zinc-700 dark:text-zinc-400">
                    Nothing found for{" "}
                    <strong className="break-words font-semibold text-zinc-900 dark:text-white">
                        &lsquo;{query}&rsquo;
                    </strong>
                    . Please try again.
                </p>
            </div>
        );
    }

    return (
        <ul {...autocomplete.getListProps()}>
            {collection.items.map((result, resultIndex) => (
                <SearchResult
                    key={result.url}
                    result={result}
                    resultIndex={resultIndex}
                    autocomplete={autocomplete}
                    collection={collection}
                    query={query}
                />
            ))}
        </ul>
    );
}
